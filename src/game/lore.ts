/** 学習セッション累計数から、解禁済みの件数を出す(3回ごとに1件)。 */
export function unlockedLoreCount(sessionCount: number): number {
  if (sessionCount <= 0) return 0;
  return Math.min(LORE_ENTRIES.length, Math.floor((sessionCount - 1) / 3) + 1);
}

/** 次の便りが解禁されるまでに必要な、残りのセッション回数。 */
export function sessionsUntilNextLore(sessionCount: number): number | null {
  const unlocked = unlockedLoreCount(sessionCount);
  if (unlocked >= LORE_ENTRIES.length) return null;
  return unlocked * 3 + 1 - sessionCount;
}
